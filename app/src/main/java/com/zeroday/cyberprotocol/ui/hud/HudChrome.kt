import kotlin.math.roundToInt

/** The three frame arts. Each is a 256x256 nine-slice generated by `tools/build_hud_assets.py`. */
enum class HudFrameVariant(val resource: Int) {
    TERMINAL(R.drawable.hud_frame_terminal),
    CLASSIC(R.drawable.hud_frame_classic),
    EDITOR(R.drawable.hud_frame_editor)
}

object HudMetrics {
    const val FRAME_SOURCE = 256
    const val FRAME_CAP = 96

    /** Bezel thickness inside the art, in art pixels. */
    const val FRAME_BEZEL = 36f

    /** Art pixels per dp: the bezel is about 10 dp thick on screen at every size. */
    const val FRAME_PX_PER_DP = 3.6f
    val FRAME_INSET = 13.dp

    const val BUTTON_WIDTH = 384
    const val BUTTON_HEIGHT = 128
    const val BUTTON_CAP = 64
    const val BUTTON_STATES = 4
}

private val StatusDotColor = Color(0xCC36E7F2)

/**
 * A panel with a stretchable frame. The corners keep their proportions at any size, only the straight edges stretch,
 * so the frame is never distorted. [fill] shows through the opening; [content] sits inside the bezel.
 */
@Composable
fun HudFrame(
    variant: HudFrameVariant,
    modifier: Modifier = Modifier,
    fill: Color = Color(0xFF101923),
    content: @Composable BoxScope.() -> Unit
) {
    val image = ImageBitmap.imageResource(variant.resource)
    Box(modifier) {
        Canvas(Modifier.matchParentSize()) {
            val scale = density / HudMetrics.FRAME_PX_PER_DP
            val inset = HudMetrics.FRAME_BEZEL * scale * 0.9f
            drawRect(fill, topLeft = Offset(inset, inset), size = Size(size.width - 2f * inset, size.height - 2f * inset))
            drawSlices(
                image,
                SliceLayout.nineSlice(
                    HudMetrics.FRAME_SOURCE, HudMetrics.FRAME_SOURCE, HudMetrics.FRAME_CAP,
                    size.width.roundToInt(), size.height.roundToInt(), scale
                )
            )
            val dotY = HudMetrics.FRAME_BEZEL * scale * 0.5f
            for (i in -1..1) {
                drawCircle(StatusDotColor, 1.6.dp.toPx(), Offset(size.width / 2f + i * 7.dp.toPx(), dotY))
            }
        }
        Box(Modifier.matchParentSize().padding(HudMetrics.FRAME_INSET), content = content)
    }
}

/** Button background with its four states (0 normal, 1 focused, 2 pressed, 3 disabled). Caps keep their proportions. */
@Composable
fun HudButtonSprite(state: Int, modifier: Modifier = Modifier) {
    val sheet = ImageBitmap.imageResource(R.drawable.hud_button_primary)
    Canvas(modifier) {
        drawSlices(
            sheet,
            SliceLayout.threeSlice(
                HudMetrics.BUTTON_WIDTH, HudMetrics.BUTTON_HEIGHT, HudMetrics.BUTTON_CAP,
                size.width.roundToInt(), size.height.roundToInt(),
                srcTop = state.coerceIn(0, HudMetrics.BUTTON_STATES - 1) * HudMetrics.BUTTON_HEIGHT
            )
        )
    }
}

private fun DrawScope.drawSlices(image: ImageBitmap, parts: List<SlicePart>) {
    for (part in parts) {
        drawImage(
            image = image,
            srcOffset = IntOffset(part.srcX, part.srcY),
            srcSize = IntSize(part.srcW, part.srcH),
            dstOffset = IntOffset(part.dstX, part.dstY),
            dstSize = IntSize(part.dstW, part.dstH),
            filterQuality = FilterQuality.High
        )
    }
}
